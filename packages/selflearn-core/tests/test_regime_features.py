"""Regime packs: breadth parity with the terminal JS, VIX expected move, no-lookahead."""

import json
import math
from pathlib import Path

import pytest

from selflearn_core.features import (
    Bar,
    BreadthPack,
    InMemoryBarSource,
    VolRegimePack,
    assemble_features,
    compute_breadth,
    compute_vol_regime,
    regime_string,
    validate_no_lookahead,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures_breadth_parity.json").read_text())
DAY = 86_400


def _bars(ts, closes):
    return [Bar(t, c, c, c, c, 1.0) for t, c in zip(ts, closes)]


def test_breadth_matches_terminal_js():
    """Same inputs as api/breadth.js buildPayload (fixture generated by running the JS)."""
    exp = FIXTURE["expected"]
    b = compute_breadth(_bars(FIXTURE["ts"], FIXTURE["rsp"]), _bars(FIXTURE["ts"], FIXTURE["spy"]))
    assert b["ratio"] == pytest.approx(exp["last"], abs=1e-5)
    assert b["dma50"] == pytest.approx(exp["dma50"], abs=1e-5)
    assert b["dma200"] == pytest.approx(exp["dma200"], abs=1e-5)
    assert b["direction"] == exp["direction"]
    assert regime_string(b) == exp["regime"]


def test_breadth_needs_sixty_points():
    ts = list(range(0, 59 * DAY, DAY))
    assert compute_breadth(_bars(ts, [1.0] * 59), _bars(ts, [2.0] * 59)) == {}
    assert regime_string({}) == ""


def test_breadth_pack_is_point_in_time():
    src = InMemoryBarSource({
        "RSP": _bars(FIXTURE["ts"], FIXTURE["rsp"]),
        "SPY": _bars(FIXTURE["ts"], FIXTURE["spy"]),
    })
    as_of = FIXTURE["ts"][199]                       # only the first 200 bars are knowable
    snap = BreadthPack(src).snapshot("ANY", as_of)
    validate_no_lookahead(snap)
    assert all(t <= as_of for t in snap.obs_ts.values())
    direct = compute_breadth(_bars(FIXTURE["ts"][:200], FIXTURE["rsp"][:200]),
                             _bars(FIXTURE["ts"][:200], FIXTURE["spy"][:200]))
    assert snap.values["ratio"] == direct["ratio"]
    feats = assemble_features([snap], as_of)
    assert "regime.breadth.direction" in feats


def test_vol_regime_divide_by_sixteen_and_alarm():
    idx = _bars([DAY, 2 * DAY], [100.0, 97.9])        # -2.1% day (2.0% at VIX 16 is 1.98 sigma)
    vix = _bars([DAY, 2 * DAY], [16.0, 25.0])         # VIX spikes on the selloff day
    v = compute_vol_regime(idx, vix)
    assert v["vix_prior_close"] == 16.0                # prior close, not the spiked reading
    assert v["daily_sigma_pct"] == pytest.approx(16 / math.sqrt(252), abs=1e-4)
    assert v["move_in_sigmas"] == pytest.approx(-2.1 / (16 / math.sqrt(252)), abs=1e-3)
    assert v["unusual_move"] is True


def test_vol_regime_normal_day_and_missing_data():
    idx = _bars([DAY, 2 * DAY], [100.0, 99.5])
    vix = _bars([DAY], [16.0])
    assert compute_vol_regime(idx, vix)["unusual_move"] is False
    assert compute_vol_regime(idx[:1], vix) == {}
    assert compute_vol_regime(idx, _bars([2 * DAY], [16.0])) == {}   # no prior-close VIX


def test_vol_pack_obs_times_never_exceed_as_of():
    src = InMemoryBarSource({
        "SPY": _bars([DAY, 2 * DAY, 3 * DAY], [100.0, 98.0, 120.0]),
        "^VIX": _bars([DAY, 2 * DAY, 3 * DAY], [16.0, 25.0, 40.0]),
    })
    snap = VolRegimePack(src).snapshot("SPY", 2 * DAY)   # day-3 bars must be invisible
    validate_no_lookahead(snap)
    assert snap.values["index_move_pct"] == pytest.approx(-2.0)
    assert snap.obs_ts["vix_prior_close"] == DAY
